use protobuf_build::Builder;
use std::fs;

fn main() {
    let proto_dir = "proto";
    let mut proto_files = Vec::new();

    // Walk the proto directory and collect all .proto files.
    for entry in fs::read_dir(proto_dir).unwrap() {
        let entry = entry.unwrap();
        let path = entry.path();
        if path.is_file() {
            if let Some(ext) = path.extension() {
                if ext == "proto" {
                    proto_files.push(path.to_string_lossy().into_owned());
                }
            }
        }
    }

    Builder::new()
        .files(&proto_files)
        .append_to_black_list("eraftpb")
        .generate();

    #[cfg(feature = "tonic-protobuf-codec")]
    tonic_codegen::generate(proto_dir);
}

/// Generates tonic clients and servers that use the rust-protobuf messages
/// generated by `protobuf-build`.
///
/// Rust names follow the grpcio generated code, e.g. service `pdpb.PD` gets
/// `pdpb::pd_client::PdClient` and `pdpb::pd_server::{Pd, PdServer}`, and its
/// method `GetMembers` becomes `get_members`.
#[cfg(feature = "tonic-protobuf-codec")]
mod tonic_codegen {
    use std::fs::{self, OpenOptions};
    use std::io::Write;
    use std::path::Path;

    use protobuf::descriptor::{FileDescriptorProto, FileDescriptorSet, ServiceDescriptorProto};
    use protobuf::descriptorx::{proto_path_to_rust_mod, RootScope, WithScope};
    use tonic_build::manual::Method;
    use tonic_build::CodeGenBuilder;

    const CODEC_PATH: &str = "crate::tonic_codec::ProtobufCodec";

    /// Appends the tonic code of the services defined in `proto_dir` to the
    /// Rust modules generated for their proto files.
    pub fn generate(proto_dir: &str) {
        let out_dir = format!("{}/protos", std::env::var("OUT_DIR").unwrap());
        // `protobuf-build` leaves the descriptors of all compiled files here.
        let desc = fs::read(format!("{}/mod.desc", out_dir)).unwrap();
        let desc: FileDescriptorSet = protobuf::parse_from_bytes(&desc).unwrap();
        let root_scope = RootScope {
            file_descriptors: desc.get_file(),
        };

        let mut code_gen = CodeGenBuilder::new();
        code_gen
            .build_transport(false)
            // Reply `UNIMPLEMENTED` for methods a server does not implement,
            // like grpcio does.
            .generate_default_stubs(true);
        for file in desc.get_file() {
            let is_imported = !Path::new(proto_dir).join(file.get_name()).exists();
            if is_imported || file.get_service().is_empty() {
                continue;
            }
            let mut code = String::new();
            for service in file.get_service() {
                let service = Service::new(file, service, &root_scope);
                code.push_str(&code_gen.generate_client(&service, "").to_string());
                code.push_str(&code_gen.generate_server(&service, "").to_string());
            }
            let path = format!("{}/{}.rs", out_dir, proto_path_to_rust_mod(file.get_name()));
            let mut out = OpenOptions::new().append(true).open(&path).unwrap();
            out.write_all(code.as_bytes()).unwrap();
        }
    }

    /// A service whose Rust name differs from its protobuf name, which
    /// `tonic_build::manual::Service` doesn't support.
    struct Service {
        rust_name: String,
        proto_name: String,
        package: String,
        methods: Vec<Method>,
    }

    impl Service {
        fn new(
            file: &FileDescriptorProto,
            service: &ServiceDescriptorProto,
            root_scope: &RootScope,
        ) -> Service {
            let rust_type = |proto_type: &str| {
                let message = root_scope.find_message(proto_type);
                format!("crate::{}", message.rust_fq_name())
            };
            let methods = service
                .get_method()
                .iter()
                .map(|m| {
                    let mut method = Method::builder()
                        .name(to_snake_case(m.get_name()))
                        .route_name(m.get_name())
                        .input_type(rust_type(m.get_input_type()))
                        .output_type(rust_type(m.get_output_type()))
                        .codec_path(CODEC_PATH);
                    if m.get_client_streaming() {
                        method = method.client_streaming();
                    }
                    if m.get_server_streaming() {
                        method = method.server_streaming();
                    }
                    method.build()
                })
                .collect();
            Service {
                rust_name: to_camel_case(service.get_name()),
                proto_name: service.get_name().to_owned(),
                package: file.get_package().to_owned(),
                methods,
            }
        }
    }

    impl tonic_build::Service for Service {
        type Comment = String;
        type Method = Method;

        fn name(&self) -> &str {
            &self.rust_name
        }

        fn package(&self) -> &str {
            &self.package
        }

        fn identifier(&self) -> &str {
            &self.proto_name
        }

        fn methods(&self) -> &[Method] {
            &self.methods
        }

        fn comment(&self) -> &[String] {
            &[]
        }
    }

    /// Splits `name` into words the same way as grpcio-compiler does.
    fn split_words(name: &str) -> Vec<&str> {
        let bytes = name.as_bytes();
        let mut words = Vec::new();
        let mut pos = 0;
        loop {
            // Skip all prefix '_'.
            while pos < bytes.len() && bytes[pos] == b'_' {
                pos += 1;
            }
            if pos == bytes.len() {
                return words;
            }
            let mut end = bytes.len();
            let mut upper_len = 0;
            let mut meet_lower = false;
            for (i, c) in bytes.iter().enumerate().skip(pos) {
                if c.is_ascii_uppercase() {
                    if meet_lower {
                        // So it should be AaA or aaA.
                        end = i;
                        break;
                    }
                    upper_len += 1;
                } else if *c == b'_' {
                    end = i;
                    break;
                } else {
                    meet_lower = true;
                    if upper_len > 1 {
                        // So it should be AAa.
                        end = i - 1;
                        break;
                    }
                }
            }
            words.push(&name[pos..end]);
            pos = end;
        }
    }

    fn to_snake_case(name: &str) -> String {
        let words: Vec<_> = split_words(name).iter().map(|w| w.to_lowercase()).collect();
        words.join("_")
    }

    fn to_camel_case(name: &str) -> String {
        split_words(name)
            .iter()
            .map(|w| format!("{}{}", &w[..1].to_uppercase(), &w[1..].to_lowercase()))
            .collect()
    }
}
